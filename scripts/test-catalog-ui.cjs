// Synthetic catalogue fixtures are disabled at the end, never represented as hospital data.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const base = process.env.ADMIN_TEST_BASE_URL || 'http://127.0.0.1:5188'
;(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'})
 const page=await browser.newPage()
 const name='目录流程测试-'+Date.now(),doctorName='模拟测试医生-'+Date.now()
 try{
  await page.goto(base+'/?demo=admin&page=admin&adminPage=catalog')
  await page.getByRole('heading',{name:'科室管理',exact:true}).waitFor()
  await page.getByLabel('科室名称',{exact:true}).fill(name)
  await page.getByRole('button',{name:'新增科室',exact:true}).click()
  await page.getByRole('status').filter({hasText:'科室已保存'}).waitFor()
  await page.getByLabel('医生姓名',{exact:true}).fill(doctorName)
  await page.getByLabel('职称',{exact:true}).fill('医师')
  await page.getByLabel('所属科室',{exact:true}).selectOption({label:name})
  await page.getByLabel('总容量',{exact:true}).fill('5')
  await page.getByRole('button',{name:'新增医生',exact:true}).click()
  await page.getByRole('status').filter({hasText:'医生与模拟号源已保存'}).waitFor()
  const row=page.getByRole('row').filter({hasText:doctorName})
  assert.ok((await row.innerText()).includes('5 / 5'))
  const login=await page.request.post(base+'/api/auth/login',{data:{username:'zhangsan',password:'123456'}})
  const patient=await login.json()
  const publicDoctors=await (await page.request.get(base+'/api/doctors')).json()
  const doctor=publicDoctors.find(d=>d.name===doctorName);assert.ok(doctor)
  const appointment=await page.request.post(base+'/api/appointments',{headers:{Authorization:'Bearer '+patient.token},data:{doctorId:doctor.id,sessionId:'walk-in',idempotencyKey:'catalog-'+Date.now()}})
  assert.equal(appointment.status(),200)
  await row.getByRole('button',{name:'编辑医生',exact:true}).click()
  await page.getByLabel('总容量',{exact:true}).fill('0')
  await page.getByRole('button',{name:'保存医生',exact:true}).click()
  await page.getByRole('alert').filter({hasText:'容量不能低于已预约数量'}).waitFor()
  await page.getByLabel('总容量',{exact:true}).fill('3')
  await page.getByRole('button',{name:'保存医生',exact:true}).click()
  await page.getByRole('status').filter({hasText:'医生与模拟号源已保存'}).waitFor()
  assert.ok((await row.innerText()).includes('2 / 3'))
  await row.getByRole('button',{name:'停用医生',exact:true}).click()
  await page.getByRole('status').filter({hasText:'医生状态已更新'}).waitFor()
  const after=await (await page.request.get(base+'/api/doctors')).json();assert.ok(!after.some(d=>d.id===doctor.id))
  const denied=await page.request.get(base+'/api/admin/catalog/doctors',{headers:{Authorization:'Bearer '+patient.token}});assert.equal(denied.status(),403)
  await page.getByRole('row').filter({hasText:name}).filter({has:page.getByRole('button',{name:'停用科室',exact:true})}).getByRole('button',{name:'停用科室',exact:true}).click()
  await page.getByRole('status').filter({hasText:'科室状态已更新'}).waitFor()
  console.log(JSON.stringify({passed:true,doctorId:doctor.id,checks:['create-department','create-doctor','public-directory','simulation-booking','capacity-conflict','preserve-booked-count','disable-doctor','patient-forbidden']}))
 }finally{await browser.close()}
})().catch(e=>{console.error(e.message);process.exitCode=1})
